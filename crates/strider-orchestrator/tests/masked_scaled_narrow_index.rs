//! PowerPC jump tables whose index is narrowed below the register width and
//! scaled by a rotate-and-mask shift. `slwi` / `sldi` lift to
//! `And(ShiftLeft(idx, k), ~(2^k - 1))`, a mask that clears only bits the
//! shift already zeroed, so the guard on `idx` bounds the scaled value exactly
//! as it does for `mulli`.
//!
//! ```text
//! PPC32
//! 10000058 sw_slwi:  clrlwi r3,r3,24 ; cmplwi r3,3 ; bgt def
//!                    lis r9,0x1000 ; addi r9,r9,0x144
//!                    rlwinm r3,r3,2,0,29
//!                    lwzx r10,r9,r3 ; add r9,r10,r9 ; mtctr r9 ; bctr
//! 100000a8 sw_mulli: the same, with `mulli r3,r3,4` in place of the rlwinm
//!
//! PPC64
//! 10000004 sw_sldi:  clrldi r3,r3,56 ; cmpldi r3,3 ; bgt def
//!                    lis r9,0x1000 ; ori r9,r9,0x100
//!                    rldicr r3,r3,3,60
//!                    ldx r10,r9,r3 ; mtctr r10 ; bctr
//! ```
//!
//! Each table is followed by words that are not code addresses, so an index
//! bound past the guard names garbage.
mod common;

use strider_orchestrator::LiftOptions;
use strider_orchestrator::opt::OptOptions;

struct Rom(&'static [(u64, &'static [u8])]);

impl strider_orchestrator::opt::ReadOnlyMemory for Rom {
    fn read(&self, addr: u64, buf: &mut [u8]) -> anyhow::Result<()> {
        for &(base, bytes) in self.0 {
            if let Some(off) = addr.checked_sub(base)
                && let Ok(off) = usize::try_from(off)
                && let Some(src) = bytes.get(off..off + buf.len())
            {
                buf.copy_from_slice(src);
                return Ok(());
            }
        }
        anyhow::bail!("unmapped {addr:#x}")
    }
}

/// Every seated `Switch` arm and the unresolved report of analysing `entry`.
fn analyze(
    arch: common::Arch,
    sections: &'static [(u64, &'static [u8])],
    entry: u64,
) -> (Vec<u64>, Vec<strider_cfg::PcodeInsnAddr>) {
    let (base, _) = sections[0];
    let mut bytes = Vec::new();
    for &(start, data) in sections {
        let off = usize::try_from(start - base).expect("offset");
        bytes.resize(off, 0);
        bytes.extend_from_slice(data);
    }
    let (mut s, cc) = common::strider_over_bytes(arch, bytes, base, Some(Box::new(Rom(sections))));
    let r = s
        .analyze(
            entry,
            &cc,
            &LiftOptions::default(),
            &OptOptions::default(),
            None,
        )
        .expect("analyze");
    let mut arms: Vec<u64> = r
        .cfg
        .regions()
        .filter_map(|reg| match &reg.terminator {
            strider_cfg::RegionTerminator::Switch { targets, .. } => Some(targets.clone()),
            _ => None,
        })
        .flatten()
        .map(|t| t.addr)
        .collect();
    arms.sort_unstable();
    (arms, r.unresolved_indirect_branches)
}

