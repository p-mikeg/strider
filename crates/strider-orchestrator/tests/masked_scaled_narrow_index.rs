#[test]
fn ppc32_mulli_scaled_narrow_index_resolves() {
    let (arms, unresolved) = analyze(common::Arch::Ppc32be, PPC32, 0x100000a8);
    assert_eq!(arms, vec![0x100000d0, 0x100000d8, 0x100000e0, 0x100000e8]);
    assert!(unresolved.is_empty(), "unresolved {unresolved:?}");
}

#[test]
fn ppc32_slwi_scaled_narrow_index_resolves() {
    let (arms, unresolved) = analyze(common::Arch::Ppc32be, PPC32, 0x10000058);
    assert_eq!(arms, vec![0x10000080, 0x10000088, 0x10000090, 0x10000098]);
    assert!(unresolved.is_empty(), "unresolved {unresolved:?}");
}

