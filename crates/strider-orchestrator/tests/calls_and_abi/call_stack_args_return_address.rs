/// That some call of each row carries exactly its expected stack arguments.
fn assert_some_call(rows: &[Row<&[Arg]>]) {
    let wrong: Vec<_> = rows
        .iter()
        .filter_map(|&(name, arch, base, bytes, want)| {
            let got = stack_args(arch, bytes.to_vec(), base);
            (!got.iter().any(|call| call == want)).then_some((name, got))
        })
        .collect();
    assert!(wrong.is_empty(), "{wrong:?}");
}

