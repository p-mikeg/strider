//! Stack arguments of real gcc -O2 code around `__builtin_return_address(0)`
//! (Linux `lock_acquire(..., _RET_IP_)`): a prologue save, or a copy in a
//! local a callee is handed, ends the collection, and so, as a known limit,
//! does an argument holding the return address.
use crate::common;
use crate::common::Arch;
use strider_ir::node::NodeKind;
use strider_ir::{IRViewer, IRWalker};

/// One expected stack argument.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Arg {
    Const(u128),
    /// An entry register value: the return address.
    Entry,
}
use Arg::{Const, Entry};

/// The stack arguments of every `Call` in `bytes` (mapped and entered at
/// `base`), in walk order.
fn stack_args(arch: Arch, bytes: Vec<u8>, base: u64) -> Vec<Vec<Arg>> {
    let (mut strider, cc) = common::strider_over_bytes(arch, bytes, base, None);
    // Bit 0 of a Thumb entry selects the instruction set.
    let entry = if arch == Arch::ArmThumb {
        base | 1
    } else {
        base
    };
    let function = strider
        .analyze(entry, &cc, &Default::default(), None)
        .expect("analyze")
        .function;
    let registers = NodeKind::Call { cc: None }.input_head_len()
        + cc.arg_passing_regs.len()
        + cc.arg_passing_regs_float.len();
    function
        .walk()
        .filter(|&n| matches!(function.node_kind(n), NodeKind::Call { .. }))
        .map(|call| {
            function
                .node_inputs(call)
                .into_iter()
                .skip(registers)
                .map(|v| match function.kind_of_value(v) {
                    NodeKind::InitialVar(_) => Entry,
                    _ => Const(function.int_const_u128(v).unwrap_or_else(|| {
                        panic!("{arch:?}: arg {:?}", function.kind_of_value(v))
                    })),
                })
                .collect()
        })
        .collect()
}

/// A case's name, arch, load and entry address, code, and expectation.
type Row<'a, T> = (&'a str, Arch, u64, &'a [u8], T);

/// `ra10(a) = sink(a, 2, ..., 9, __builtin_return_address(0)) + 1`.
const RA10: &[Arg] = &[Const(9), Entry];
/// `ra10`'s stack arguments where four registers carry the first four.
const RA10_FOUR_REGS: &[Arg] = &[Const(5), Const(6), Const(7), Const(8), Const(9), Entry];
/// `raw_lock(l) = lock_acquire(l, 0, 0, 0, 1, 0, __builtin_return_address(0))`.
const RAW_LOCK_FOUR_REGS: &[Arg] = &[Const(1), Const(0), Entry];

