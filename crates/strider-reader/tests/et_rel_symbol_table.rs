/// The `call`'s rel32 field, read back through the relocating reader.
fn patched_rel32(bytes: &[u8]) -> i32 {
    let dir = std::env::temp_dir().join(format!("strider-rel-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("tmpdir");
    let path = dir.join("t.o");
    std::fs::write(&path, bytes).expect("write");
    let elf = load_elf(&path).expect("load_elf");
    let obj = elf.checked_file().expect("the mapped file is unchanged");
    // `.text` is rebased off the synthetic ET_REL image base; the field is the
    // `call`'s rel32, one byte into it.
    let field_addr = {
        use object::Object as _;
        strider_reader::elf::ElfSectionLayout::new(&obj)
            .section_base(&obj.section_by_name(".text").expect(".text"))
            + 1
    };
    let regions = elf
        .regions(
            strider_reader::elf::RegionSource::Auto,
            strider_reader::elf::LoadFilter::AllAllocatable,
            true,
        )
        .expect("regions");
    let mut field = [0u8; 4];
    assert!(
        regions
            .iter()
            .any(|r| r.read(field_addr, &mut field) == Some(4)),
        "no region covers the call's rel32 field"
    );
    let _ = std::fs::remove_file(&path);
    i32::from_le_bytes(field)
}

#[test]
fn an_object_files_relocations_ignore_a_decoy_dynsym() {
    let without = patched_rel32(&unhex(REL_NODYN));
    let with = patched_rel32(&unhex(REL_DYN));
    assert_eq!(
        with, without,
        "a decoy .dynsym changed which symbol the relocation resolved against"
    );
    // `.text.target` is rebased above `.text`, so the displacement reaches it.
    assert_eq!(without, 0xb);
}
